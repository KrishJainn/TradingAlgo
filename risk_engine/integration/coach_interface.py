@dataclass
class CoachDecision:
    """Complete output of the risk-engine pipeline for a single bar.

    Encapsulates every sizing, allocation, and risk decision made by
    the coach so that downstream systems (execution, dashboard, logging)
    have a single, self-describing object to consume.

    Attributes
    ----------
    agent_weights : dict[str, float]
        Blended weights (HRP strategic + online tactical) per agent.
        Sums to approximately 1.0.
    position_sizes : dict[str, float]
        Kelly-sized positions per agent as a fraction of portfolio NAV.
        Positive = long, negative = short.  Incorporates direction,
        confidence, regime, and constraint adjustments.
    risk_budget : dict[str, float]
        Risk allocation per agent as a fraction of total portfolio risk.
        Derived from HRP weights scaled by agent volatility contribution.
    total_exposure : float
        Net exposure of the portfolio as a fraction of NAV:
            total_exposure = sum(position_sizes.values())
        Positive means net long, negative means net short.
    cost_estimate : float
        Estimated round-trip transaction cost for executing all proposed
        position changes, expressed in basis points of portfolio NAV.
    constraints_applied : list[str]
        Human-readable descriptions of every constraint that fired during
        this bar.  Empty list means no constraint violations.
    meta_label_proba : float
        Predicted probability from the meta-labeling model that the
        aggregated signal will be profitable.  Range [0, 1].
        A value below 0.5 typically suppresses the trade.
    conformal_interval : tuple[float, float]
        Prediction interval for the expected portfolio return at the
        configured coverage level (default 90%):
            (lower_bound, upper_bound)
        Generated by the conformal predictor (Vovk et al. 2005).
    timestamp : str
        ISO-8601 UTC timestamp when this decision was produced.
    """

    agent_weights: dict[str, float]
    position_sizes: dict[str, float]
    risk_budget: dict[str, float]
    total_exposure: float
    cost_estimate: float
    constraints_applied: list[str]
    meta_label_proba: float
    conformal_interval: tuple[float, float]
    timestamp: str

    def to_dict(self) -> dict[str, Any]:
        """Serialize the decision to a plain dictionary.

        Returns
        -------
        dict[str, Any]
            JSON-compatible representation of the decision.
        """
        return {
            "agent_weights": self.agent_weights,
            "position_sizes": self.position_sizes,
            "risk_budget": self.risk_budget,
            "total_exposure": self.total_exposure,
            "cost_estimate": self.cost_estimate,
            "constraints_applied": self.constraints_applied,
            "meta_label_proba": self.meta_label_proba,
            "conformal_interval": list(self.conformal_interval),
            "timestamp": self.timestamp,
        }

    @property
    def gross_exposure(self) -> float:
        """Sum of absolute position sizes.

        Formula
        -------
            gross = sum(|pos_i|)  for all agents i

        Returns
        -------
        float
            Non-negative gross exposure as a fraction of NAV.
        """
        return sum(abs(v) for v in self.position_sizes.values())

    @property
    def n_active_positions(self) -> int:
        """Count of agents with non-zero position sizes.

        Returns
        -------
        int
            Number of agents currently allocated capital.
        """
        return sum(1 for v in self.position_sizes.values() if abs(v) > 1e-8)


