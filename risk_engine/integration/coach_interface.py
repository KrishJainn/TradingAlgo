"""Coach-to-risk-engine integration layer.

Orchestrates the full position-sizing pipeline: alpha aggregation,
risk estimation, HRP allocation, online weight blending, Kelly sizing,
constraint enforcement, meta-label filtering, and cost estimation.

The pipeline implements a layered decision framework inspired by:

1. Grinold & Kahn (1999) -- inverse-variance alpha aggregation.
2. Lopez de Prado (2016) -- Hierarchical Risk Parity allocation.
3. Cover (1991) / Cesa-Bianchi & Lugosi (2006) -- online exponential
   weights for tactical blending.
4. Kelly (1956) / Thorp (2008) -- position sizing via fractional Kelly.
5. Lopez de Prado (2018) -- meta-labeling for trade filtering.
6. Vovk et al. (2005) -- conformal prediction for uncertainty intervals.

References
----------
Grinold, R.C. & Kahn, R.N. (1999). *Active Portfolio Management*, 2nd ed.
Lopez de Prado, M. (2016). J. Portfolio Management, 42(4), 59-69.
Cover, T.M. (1991). Mathematical Finance, 1(1), 1-29.
Kelly, J.L. (1956). Bell System Technical Journal, 35(4), 917-926.
Thorp, E.O. (2008). Handbook of Asset and Liability Management.
Lopez de Prado, M. (2018). *Advances in Financial Machine Learning*, Wiley.
Vovk, V., Gammerman, A. & Shafer, G. (2005). *Algorithmic Learning in a
    Random World*, Springer.
"""

